"""
Regenerate the checked-in SQL for the per-dropdown master tables.

Anyone cloning this repo needs the 122 `master_*` tables and their option rows.
`migrate_split_master_tables.py` can only build them from an existing populated
`masters` table, which a fresh clone does not have — so the tables and their data
are written out here as plain SQL that a new environment can load directly.

Writes two files, both safe to re-run against a live database:

    database/tables/master_tables.sql   CREATE TABLE IF NOT EXISTS x123
    database/seeds/master_data.sql      INSERT … ON DUPLICATE KEY UPDATE id=id (add only)

Run after adding or renaming a dropdown, and commit both files:

    python generate_master_sql.py
"""
import os

from sqlalchemy import text

from portal import InitApp
from portal.models import db

app = InitApp().app()

TABLES_OUT = 'database/tables/master_tables.sql'
SEEDS_OUT = 'database/seeds/master_data.sql'

HEADER = """-- SKOVO — master tables (one per dropdown)
-- Auto-generated by generate_master_sql.py — do not edit by hand.
--
-- Every dropdown in the four portals has its own table here rather than sharing
-- one `masters` table keyed by a `type` column. `master_registry` maps a
-- dropdown's type name to its table, and is what makes the generic
-- sp_master_* procedures safe: they resolve the table name through it instead of
-- interpolating caller input into dynamic SQL.
--
-- {n} tables. Load with:  mysql -u root -p SKOVO < database/tables/master_tables.sql
-- Then the rows:          mysql -u root -p SKOVO < database/seeds/master_data.sql
-- Then the procedures:    mysql -u root -p SKOVO < database/stored_procedures/master_tables.sql
"""

REGISTRY_DDL = """
-- ------------------------------------------------------------
-- Table: master_registry  (type name -> table name)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `master_registry` (
  `id` CHAR(36) NOT NULL,
  `type` VARCHAR(64) NOT NULL,
  `table_name` VARCHAR(80) NOT NULL,
  `label` VARCHAR(150) NOT NULL,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_master_registry_type` (`type`),
  UNIQUE KEY `uq_master_registry_table` (`table_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
"""

# COLLATE is explicit: the server default for utf8mb4 is utf8mb4_0900_ai_ci, and
# comparing those rows against the utf8mb4_unicode_ci tables raises
# "Illegal mix of collations" the moment anything joins across them.
TABLE_DDL = """
-- ------------------------------------------------------------
-- Table: {table}   ({type})
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `{table}` (
  `id` CHAR(36) NOT NULL,
  `value` VARCHAR(100) NOT NULL,
  `label` VARCHAR(150) NOT NULL,
  `sort_order` INT NULL DEFAULT 0,
  `is_active` TINYINT(1) NULL DEFAULT 1,
  `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `created_by` CHAR(36) NULL,
  `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `updated_by` CHAR(36) NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_{table}_value` (`value`),
  KEY `ix_{table}_active` (`is_active`, `sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
"""


def esc(v):
    """MySQL string literal, or NULL."""
    if v is None:
        return 'NULL'
    return "'" + str(v).replace('\\', '\\\\').replace("'", "''") + "'"


def main():
    with app.app_context():
        rows = db.session.execute(text(
            "SELECT `type`, `table_name`, `label` FROM `master_registry` "
            "WHERE `is_active` = 1 ORDER BY `type`")).mappings().all()
        if not rows:
            print('master_registry is empty — run migrate_split_master_tables.py first')
            return

        # ── DDL ─────────────────────────────────────────────────────────────
        parts = [HEADER.format(n=len(rows) + 1), REGISTRY_DDL]
        for r in rows:
            parts.append(TABLE_DDL.format(table=r['table_name'], type=r['type']))

        os.makedirs(os.path.dirname(TABLES_OUT), exist_ok=True)
        with open(TABLES_OUT, 'w', encoding='utf-8') as f:
            f.write('\n'.join(parts))

        # ── seed rows ───────────────────────────────────────────────────────
        # Add-only: a row that already exists is left exactly as it is. Every
        # deploy loads this file, and refreshing label / sort_order / is_active
        # here silently undid what an admin changed in Admin > Masters -- the
        # masters are admin-editable, so the database is the source of truth.
        # `id`=`id` rather than INSERT IGNORE so real errors still surface.
        seed = [
            '-- SKOVO — master table option rows',
            '-- Auto-generated by generate_master_sql.py — do not edit by hand.',
            '--',
            '-- Add-only: re-running inserts missing options and never changes an',
            '-- existing one, so edits made in Admin > Masters survive every deploy.',
            '',
        ]

        seed.append('-- registry')
        for r in rows:
            seed.append(
                "INSERT INTO `master_registry` (`id`,`type`,`table_name`,`label`,`is_active`) "
                f"VALUES (UUID(), {esc(r['type'])}, {esc(r['table_name'])}, {esc(r['label'])}, 1) "
                "ON DUPLICATE KEY UPDATE `id`=`id`;")

        total = 0
        for r in rows:
            table = r['table_name']
            opts = db.session.execute(text(
                f"SELECT `id`,`value`,`label`,`sort_order`,`is_active` FROM `{table}` "
                "ORDER BY `sort_order`, `label`")).mappings().all()
            if not opts:
                continue
            seed.append('')
            seed.append(f"-- {table}  ({len(opts)} options)")
            for o in opts:
                seed.append(
                    f"INSERT INTO `{table}` (`id`,`value`,`label`,`sort_order`,`is_active`) VALUES "
                    f"({esc(o['id'])}, {esc(o['value'])}, {esc(o['label'])}, "
                    f"{o['sort_order'] if o['sort_order'] is not None else 0}, "
                    f"{1 if o['is_active'] else 0}) "
                    "ON DUPLICATE KEY UPDATE `id`=`id`;")
                total += 1

        os.makedirs(os.path.dirname(SEEDS_OUT), exist_ok=True)
        with open(SEEDS_OUT, 'w', encoding='utf-8') as f:
            f.write('\n'.join(seed) + '\n')

        print(f'{TABLES_OUT}   {len(rows) + 1} tables')
        print(f'{SEEDS_OUT}   {len(rows)} registry rows + {total} option rows')


if __name__ == '__main__':
    main()
